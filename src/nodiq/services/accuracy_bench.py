def _contour_mask(contour, shape):
    m = np.zeros(shape[:2], np.uint8)
    cv2.drawContours(m, [np.asarray(contour, dtype=np.int64)], -1, 255, -1)
    return m


def _box_mask(box, shape):
    """box = {cx, cy, w, h} normalized [0,1] (YOLO) or pixel dict."""
    m = np.zeros(shape[:2], np.uint8)
    h, w = shape[:2]
    if 0 < box["cx"] <= 1 and 0 < box["cy"] <= 1 and box["w"] <= 1:
        x0 = int((box["cx"] - box["w"] / 2) * w)
        y0 = int((box["cy"] - box["h"] / 2) * h)
        x1 = int((box["cx"] + box["w"] / 2) * w)
        y1 = int((box["cy"] + box["h"] / 2) * h)
    else:
        x0, y0 = int(box["cx"] - box["w"] / 2), int(box["cy"] - box["h"] / 2)
        x1, y1 = int(box["cx"] + box["w"] / 2), int(box["cy"] + box["h"] / 2)
    cv2.rectangle(m, (max(0, x0), max(0, y0)),
                  (min(w - 1, x1), min(h - 1, y1)), 255, -1)
    return m


def mask_iou(mask_a, mask_b):
    inter = int(np.logical_and(mask_a > 0, mask_b > 0).sum())
    union = int(np.logical_or(mask_a > 0, mask_b > 0).sum())
    return inter / union if union else 0.0


def _bbox_of_mask(mask):
    ys, xs = np.nonzero(mask > 0)
    if not len(xs):
        return None
    return int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())


def _boxes_overlap(a, b, pad=1):
    return not (a[2] + pad < b[0] or b[2] + pad < a[0] or
                a[3] + pad < b[1] or b[3] + pad < a[1])


def _pred_mask(item, shape):
    """Accept a prediction as {"mask": ndarray}, a 2-D uint8 mask array, or
    a raw OpenCV contour (Nx1x2 int array)."""
    if isinstance(item, dict) and "mask" in item:
        return item["mask"].astype(np.uint8)
    if isinstance(item, np.ndarray) and item.ndim == 2:
        return item.astype(np.uint8)
    return _contour_mask(item, shape)


def match_instances(gt_items, pred_contours, shape, iou_threshold=0.50):
    """Greedy IoU matching of ground-truth items vs predicted instances.

    gt_items / pred_contours: lists of {"mask": np.ndarray} or raw contour
    arrays (predictions only).  Returns TP/FP/FN, per-pair IoUs, and
    matched-area pairs for Phase 7.  Each GT matches at most one prediction
    (highest IoU first).
    """
    gt_masks = [g["mask"] if "mask" in g
                else _box_mask(g["box"], shape) for g in gt_items]
    pred_masks = [_pred_mask(p, shape) for p in pred_contours]
    # bbox prefilter: only pixel-IoU pairs whose bounding boxes overlap
    gt_bboxes = [_bbox_of_mask(m) for m in gt_masks]
    pred_bboxes = [_bbox_of_mask(m) for m in pred_masks]
    pairs = []
    for gi, gm in enumerate(gt_masks):
        gb = gt_bboxes[gi]
        if gb is None:
            continue
        for pi, pm in enumerate(pred_masks):
            pb = pred_bboxes[pi]
            if pb is None or not _boxes_overlap(gb, pb):
                continue
            iou = mask_iou(gm, pm)
            if iou > 0:
                pairs.append((iou, gi, pi))
    pairs.sort(reverse=True)
    matched_gt, matched_pred, ious, area_pairs = set(), set(), [], []
    for iou, gi, pi in pairs:
        if iou < iou_threshold:
            break                      # sorted: every later pair is lower
        if gi in matched_gt or pi in matched_pred:
            continue
        matched_gt.add(gi)
        matched_pred.add(pi)
        ious.append(iou)
        gt_area = int((gt_masks[gi] > 0).sum())
        pred_area = int((pred_masks[pi] > 0).sum())
        area_pairs.append({"gt_area_px": gt_area, "pred_area_px": pred_area,
                           "abs_area_error_px": abs(pred_area - gt_area),
                           "rel_area_error": (abs(pred_area - gt_area) /
                                              gt_area if gt_area else None),
                           "iou": iou})
    tp = len(matched_gt)
    fn = len(gt_masks) - tp
    fp = len(pred_masks) - len(matched_pred)
    precision = tp / (tp + fp) if (tp + fp) else None
    recall = tp / (tp + fn) if (tp + fn) else None
    f1 = (2 * precision * recall / (precision + recall)
          if precision and recall else None)
    return {
        "iou_threshold": iou_threshold,
        "tp": tp, "fp": fp, "fn": fn,
        "precision": precision, "recall": recall, "f1": f1,
        "mean_iou": (sum(ious) / len(ious)) if ious else None,
        "median_iou": (float(np.median(ious))) if ious else None,
        "area_pairs": area_pairs,
    }


