def _error_buckets(synth_results, review_probes):
    """Aggregate error buckets from the evidence actually collected."""
    buckets = {}
    for s in synth_results:
        m = s["matching"]
        buckets.setdefault("synthetic_overall", {"cases": 0, "tp": 0,
                                                 "fp": 0, "fn": 0,
                                                 "count_err": 0,
                                                 "iso_err_pp": 0.0,
                                                 "jis_err_pp": 0.0})
        b = buckets["synthetic_overall"]
        b["cases"] += 1
        b["tp"] += m["tp"]
        b["fp"] += m["fp"]
        b["fn"] += m["fn"]
        b["count_err"] += s["count_abs_error"]
        b["iso_err_pp"] += s["iso_abs_error_pp"]
        b["jis_err_pp"] += s["jis_abs_error_pp"]
    if buckets.get("synthetic_overall"):
        b = buckets["synthetic_overall"]
        n = max(1, b["cases"])
        b["mean_count_err"] = b["count_err"] / n
        b["mean_iso_err_pp"] = b["iso_err_pp"] / n
        b["mean_jis_err_pp"] = b["jis_err_pp"] / n
    fp_total = sum(p.get("human_fp_total", 0) for p in review_probes)
    fp_carried = sum(p.get("human_fp_still_produced", 0)
                     for p in review_probes)
    if fp_total:
        buckets["human_review_fp"] = {
            "human_fp_total": fp_total,
            "still_produced_by_current_pipeline": fp_carried,
            "eliminated_vs_legacy_validator": fp_total - fp_carried,
            "carryover_rate": fp_carried / fp_total,
        }
    return buckets
