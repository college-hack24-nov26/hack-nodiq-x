def _candidate_boxes(image):
    rows = [r for r in _load_review_rows()
            if r["image"] == image and r.get("reviewer_label")]
    out = []
    for r in rows:
        x, y = float(r["cx"]) * 2 - float(r["width"]) / 2, \
            float(r["cy"]) * 2 - float(r["height"]) / 2
        # candidates_full/sample_review store center + width/height at the
        # 1920 working scale; cx/cy are pixel centers already.
        x = float(r["cx"]) - float(r["width"]) / 2
        y = float(r["cy"]) - float(r["height"]) / 2
        out.append({"box": {"cx": x + float(r["width"]) / 2,
                            "cy": y + float(r["height"]) / 2,
                            "w": float(r["width"]),
                            "h": float(r["height"])},
                    "label": r["reviewer_label"],
                    "candidate_id": r["candidate_id"]})
    return out


def score_against_review(image, pred_contours, shape):
    """Of the human-labeled candidates on one image, how many survive in the
    CURRENT production output?  TP carryover = recalled human TPs; FP
    carryover = human FPs still produced.  This is evidence about precision
    only (n_TP=5 repo-wide) and never a recall claim."""
    labeled = _candidate_boxes(image)
    if not labeled:
        return {"image": image, "available": False}
    pred_masks = [_contour_mask(c, shape) for c in pred_contours]
    pred_bboxes = [_bbox_of_mask(m) for m in pred_masks]
    per_label = {"true_nodule": {"total": 0, "carried": 0},
                 "false_positive": {"total": 0, "carried": 0}}
    carried_fp_ids = []
    for cand in labeled:
        bm = _box_mask(cand["box"], shape)
        cb = _bbox_of_mask(bm)
        best = 0.0
        if cb is not None:
            for pi, pm in enumerate(pred_masks):
                pb = pred_bboxes[pi]
                if pb is None or not _boxes_overlap(cb, pb, pad=4):
                    continue
                best = max(best, mask_iou(bm, pm))
        lab = cand["label"]
        if lab in per_label:
            per_label[lab]["total"] += 1
            if best >= REVIEW_MATCH_IOU:
                per_label[lab]["carried"] += 1
                if lab == "false_positive":
                    carried_fp_ids.append(cand["candidate_id"])
    fp = per_label["false_positive"]
    tp = per_label["true_nodule"]
    return {
        "image": image,
        "available": True,
        "match_iou": REVIEW_MATCH_IOU,
        "human_tp_total": tp["total"],
        "human_tp_detected": tp["carried"],
        "human_fp_total": fp["total"],
        "human_fp_still_produced": fp["carried"],
        "human_fp_eliminated": fp["total"] - fp["carried"],
        "fp_carryover_rate": (fp["carried"] / fp["total"]
                              if fp["total"] else None),
        "carried_fp_candidate_ids": carried_fp_ids,
    }


