# Phase 8/22 — synthetic known-geometry cases (exact analytic ground truth)
# ---------------------------------------------------------------------------
def _draw_particle(img, kind, cx, cy, a, b=None, angle=0.0):
    """Draw one particle; return its analytic (area_px, marumi)."""
    if kind == "circle":
        cv2.circle(img, (cx, cy), a, 0, -1)
        area = math.pi * a * a
        return area, 1.0
    if kind == "ellipse":
        cv2.ellipse(img, (cx, cy), (a, b), angle, 0, 360, 0, -1)
        area = math.pi * a * b
        return area, b / a
    raise ValueError(kind)


def synthetic_case(name):
    """Deterministic 1920-wide cases with analytically known geometry.

    Each case returns (image_bgr, gt_particles) where gt_particles is a list
    of {area_px, marumi, touches_border} — the pixel-exact ground truth.
    """
    img = np.full((1080, 1920, 3), 235, np.uint8)
    gts = []
    rng = np.random.RandomState(20260917)

    if name == "clean_round":
        # 8 interior circles r=45 -> marumi 1.0, ISO 100, JIS 100
        for i in range(8):
            cx = 150 + (i % 4) * 420
            cy = 300 + (i // 4) * 480
            area, mar = _draw_particle(img, "circle", cx, cy, 45)
            gts.append({"area_px": area, "marumi": mar,
                        "touches_border": False})
    elif name == "mixed_round_irregular":
        # 4 circles r=50 (round) + 4 ellipses 70x25 (b/a~0.357 irregular)
        for i in range(4):
            area, mar = _draw_particle(img, "circle", 200 + i * 420, 300, 50)
            gts.append({"area_px": area, "marumi": mar,
                        "touches_border": False})
        for i in range(4):
            area, mar = _draw_particle(img, "ellipse", 200 + i * 420, 780,
                                       70, 25)
            gts.append({"area_px": area, "marumi": mar,
                        "touches_border": False})
    elif name == "size_gradient":
        # circles r = 8, 14, 22, 34, 50 — exercises the area floor / smalls
        radii = [8, 14, 22, 34, 50]
        for i, r in enumerate(radii):
            area, mar = _draw_particle(img, "circle", 180 + i * 350, 540, r)
            gts.append({"area_px": area, "marumi": mar,
                        "touches_border": False})
    elif name == "touching_pair":
        # two r=40 circles overlapping by ~1/3 -> GT = 2 particles; the
        # engine may merge them (documented failure mode to MEASURE)
        area1, mar = _draw_particle(img, "circle", 900, 480, 40)
        area2, _ = _draw_particle(img, "circle", 965, 480, 40)
        gts = [{"area_px": area1, "marumi": mar, "touches_border": False},
               {"area_px": area2, "marumi": mar, "touches_border": False}]
    elif name == "border_case":
        # 3 interior circles + 1 clipped by the frame edge
        for cx in (300, 900, 1500):
            area, mar = _draw_particle(img, "circle", cx, 500, 42)
            gts.append({"area_px": area, "marumi": mar,
                        "touches_border": False})
        area, mar = _draw_particle(img, "circle", 8, 300, 36)
        gts.append({"area_px": area, "marumi": mar, "touches_border": True})
    elif name == "low_contrast":
        # matrix 200, particles 150 (mild contrast) — 5 circles
        img[:] = 200
        cv2.rectangle(img, (0, 0), (1919, 1079), (200, 200, 200), -1)
        for i in range(5):
            cv2.circle(img, (220 + i * 370, 540), 40, 150, -1)
            area = math.pi * 40 * 40
            gts.append({"area_px": area, "marumi": 1.0,
                        "touches_border": False})
    else:
        raise ValueError("unknown synthetic case: %s" % name)
    _ = rng  # reserved; cases are fully deterministic without noise
    return img, gts


def _gt_nodularity(gts):
    """GT ISO (area-weighted, all particles) + JIS (count-weighted) from the
    analytic particle table — same definitions as the engine, exact inputs."""
    from nodiq.pipelines.analyze_with_recovery import jis_bucket
    area_total = sum(g["area_px"] for g in gts)
    area_round = sum(g["area_px"] for g in gts if g["marumi"] >= 0.6)
    iso = area_round / area_total * 100 if area_total else 0.0
    counts = [0, 0, 0, 0, 0]
    for g in gts:
        counts[jis_bucket(g["marumi"]) - 1] += 1
    n = len(gts)
    jis = ((0.3 * counts[1] + 0.7 * counts[2] + 0.9 * counts[3] +
            counts[4]) / n * 100) if n else 0.0
    return {"iso_pct": iso, "jis_pct": jis, "count": n, "jis_counts": counts}


def evaluate_synthetic_case(name):
    """Run production engine on one synthetic case; score vs analytic GT."""
    from nodiq.pipelines.nodularity_pipeline import analyze_image
    img, gts = synthetic_case(name)
    res = analyze_image(img, with_accuracy=False, stem=name)
    gt = _gt_nodularity(gts)
    # instance matching: GT masks reconstructed analytically per particle
    shape = res["gray"].shape
    # scale GT geometry 1920 stays 1920 (engine keeps width)
    gt_items = _synthetic_gt_masks(name, shape)
    m = match_instances(gt_items, res["contours"], shape,
                        iou_threshold=0.50)
    return {
        "case": name,
        "kind": "SYNTHETIC",
        "gt": gt,
        "pred": {"count": res["count"], "iso_pct": res["iso_pct"],
                 "iso_inframe_pct": res["iso_inframe_pct"],
                 "jis_pct": res["jis_pct"],
                 "border_count": sum(1 for r in res["rows"]
                                     if r["touches_border"])},
        "iso_abs_error_pp": abs(res["iso_pct"] - gt["iso_pct"]),
        "jis_abs_error_pp": abs(res["jis_pct"] - gt["jis_pct"]),
        "count_abs_error": abs(res["count"] - gt["count"]),
        "matching": {k: v for k, v in m.items() if k != "area_pairs"},
        "area_pairs": m["area_pairs"],
        "rows": res["rows"],
    }


def _synthetic_gt_masks(name, shape):
    """Rebuild per-particle GT masks for matching (deterministic geometry)."""
    masks = []
    def add_circle(cx, cy, r):
        m = np.zeros(shape[:2], np.uint8)
        cv2.circle(m, (cx, cy), r, 255, -1)
        masks.append({"mask": m})
    def add_ellipse(cx, cy, a, b):
        m = np.zeros(shape[:2], np.uint8)
        cv2.ellipse(m, (cx, cy), (a, b), 0, 0, 360, 255, -1)
        masks.append({"mask": m})
    if name == "clean_round":
        for i in range(8):
            add_circle(150 + (i % 4) * 420, 300 + (i // 4) * 480, 45)
    elif name == "mixed_round_irregular":
        for i in range(4):
            add_circle(200 + i * 420, 300, 50)
        for i in range(4):
            add_ellipse(200 + i * 420, 780, 70, 25)
    elif name == "size_gradient":
        for i, r in enumerate([8, 14, 22, 34, 50]):
            add_circle(180 + i * 350, 540, r)
    elif name == "touching_pair":
        add_circle(900, 480, 40)
        add_circle(965, 480, 40)
    elif name == "border_case":
        for cx in (300, 900, 1500):
            add_circle(cx, 500, 42)
        add_circle(8, 300, 36)
    elif name == "low_contrast":
        for i in range(5):
            add_circle(220 + i * 370, 540, 40)
    return masks


