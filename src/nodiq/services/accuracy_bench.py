def render_overlay(image_bgr, gt_items, pred_contours, out_path):
    """TP green, FP red, FN blue — diagnostic evidence, not marketing."""
    shape = image_bgr.shape
    canvas = image_bgr.copy()
    gt_masks = [g["mask"] if "mask" in g else _box_mask(g["box"], shape)
                for g in gt_items]
    pred_masks = [_pred_mask(p, shape) for p in pred_contours]
    # recompute assignment to know which pred/gt indices matched
    pairs = []
    for gi, gm in enumerate(gt_masks):
        for pi, pm in enumerate(pred_masks):
            iou = mask_iou(gm, pm)
            if iou > 0:
                pairs.append((iou, gi, pi))
    pairs.sort(reverse=True)
    mg, mp = set(), set()
    for iou, gi, pi in pairs:
        if gi in mg or pi in mp:
            continue
        mg.add(gi)
        mp.add(pi)
        cv2.drawContours(canvas, [np.asarray(pred_contours[pi],
                                             dtype=np.int64)], -1,
                         (0, 255, 0), 2)
    for pi in range(len(pred_masks)):
        if pi not in mp:
            cv2.drawContours(canvas, [np.asarray(pred_contours[pi],
                                                 dtype=np.int64)], -1,
                             (0, 0, 255), 2)
    for gi, gm in enumerate(gt_masks):
        if gi not in mg:
            ys, xs = np.nonzero(gm)
            if len(xs):
                cv2.rectangle(canvas, (int(xs.min()), int(ys.min())),
                              (int(xs.max()), int(ys.max())), (255, 0, 0), 2)
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(out_path), canvas)
    return {"tp": len(mg), "fp": len(pred_masks) - len(mp),
            "fn": len(gt_masks) - len(mg), "path": str(out_path)}


