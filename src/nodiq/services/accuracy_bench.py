def ground_truth_record(image_id, image_path, source, annotation_type):
    """Schema-conformant GT record; unknown fields stay null (never guessed)."""
    img = cv2.imread(str(image_path))
    h = int(img.shape[0]) if img is not None else None
    w = int(img.shape[1]) if img is not None else None
    yolo = _load_yolo_boxes(image_id)
    return {
        "image_id": image_id,
        "image_path": str(image_path),
        "width": w,
        "height": h,
        "pixel_scale_um_per_px": None,      # no calibrated image in repo
        "ground_truth_nodule_count": None,  # no count-level GT available
        "ground_truth_masks": None,
        "ground_truth_boxes": yolo,         # only if expert YOLO appears
        "ground_truth_nodularity_pct": None,
        "ground_truth_border_count": None,
        "ground_truth_metadata": None,
        "source": source,                   # A | B | C | D | E | F
        "annotation_type": annotation_type,
    }


def _load_yolo_boxes(stem):
    """Expert YOLO boxes for one image, or None (class 0 = graphite nodule)."""
    f = GT_DIR / (stem + ".txt")
    if not f.is_file():
        return None
    boxes = []
    for line in f.read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) >= 5 and parts[0] == "0":
            cx, cy, bw, bh = (float(v) for v in parts[1:5])
            boxes.append({"cx": cx, "cy": cy, "w": bw, "h": bh})
    return boxes or None


def _load_review_rows():
    if not REVIEW_CSV.is_file():
        return []
    with open(REVIEW_CSV, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _label_counts(rows):
    from collections import Counter
    return dict(Counter(r.get("reviewer_label", "") or "(unlabeled)"
                        for r in rows))


