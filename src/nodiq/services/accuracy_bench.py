def sensitivity_sweep(image_paths, factors=(0.5, 0.75, 1.0, 1.25, 1.5)):
    """Sweep the detector's size-acceptance parameter (legacy.min_grainsize —
    the classical pipeline's analog of a detection threshold).  Constants are
    patched in-process and RESTORED; nothing is persisted to production."""
    import sys
    if str(NODULARITY_MAIN) not in sys.path:
        sys.path.insert(0, str(NODULARITY_MAIN))
    import nodularity as legacy
    from nodiq.pipelines.nodularity_pipeline import analyze_image
    baseline = legacy.min_grainsize
    rows = []
    try:
        for factor in factors:
            legacy.min_grainsize = baseline * factor
            for path in image_paths:
                res = analyze_image(str(path), with_accuracy=False,
                                    stem=Path(path).stem)
                rows.append({
                    "factor": factor,
                    "min_grainsize": round(legacy.min_grainsize, 6),
                    "image": Path(path).stem,
                    "count": res["count"],
                    "iso_pct": res["iso_pct"],
                    "jis_pct": res["jis_pct"],
                })
    finally:
        legacy.min_grainsize = baseline
    return rows


def area_floor_sweep(image_paths, ratios=(0.25, 0.5, 1.0, 2.0)):
    """Sweep the production consistency-gate area floor (AREA_FLOOR_RATIO,
    nominal 800 px^2 at 1920 width) — the parameter that currently excludes
    the human-labeled small TPs.  Patched in-process and restored."""
    import nodiq.pipelines.analyze_with_recovery as rec
    from nodiq.pipelines.nodularity_pipeline import analyze_image
    baseline = rec.AREA_FLOOR_RATIO
    rows = []
    try:
        for factor in ratios:
            rec.AREA_FLOOR_RATIO = baseline * factor
            for path in image_paths:
                res = analyze_image(str(path), with_accuracy=False,
                                    stem=Path(path).stem)
                rows.append({
                    "factor": factor,
                    "area_floor_px": rec.area_floor(rec.AREA_FLOOR_RATIO,
                                                    res["gray"].shape[0],
                                                    res["gray"].shape[1]),
                    "image": Path(path).stem,
                    "count": res["count"],
                    "iso_pct": res["iso_pct"],
                    "jis_pct": res["jis_pct"],
                })
    finally:
        rec.AREA_FLOOR_RATIO = baseline
    return rows


